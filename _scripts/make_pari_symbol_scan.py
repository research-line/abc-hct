"""Emit a PARI/GP modular-symbol scan for high-quality Frey triples.

The emitted GP code uses msfromell(E) and evaluates the period-normalized
symbols x^+, x^- along the canonical continued-fraction/Farey path from
0 to lambda=a/(a+b).
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
import argparse
from pathlib import Path


@dataclass(frozen=True)
class Triple:
    a: int
    b: int
    label: str
    q: float

    @property
    def c(self) -> int:
        return self.a + self.b


