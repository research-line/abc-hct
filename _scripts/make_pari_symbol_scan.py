def continued_fraction(frac: Fraction) -> list[int]:
    n, d = frac.numerator, frac.denominator
    out: list[int] = []
    while d:
        q, n = divmod(n, d)
        out.append(q)
        n, d = d, n
    return out


def convergents(cf: list[int]) -> list[Fraction]:
    conv: list[Fraction] = []
    p0, p1 = 0, 1
    q0, q1 = 1, 0
    for a in cf:
        p0, p1 = p1, a * p1 + p0
        q0, q1 = q1, a * q1 + q0
        conv.append(Fraction(p1, q1))
    return conv


def farey_edges(frac: Fraction) -> list[tuple[Fraction, Fraction]]:
    conv = convergents(continued_fraction(frac))
    if conv[0] != 0:
        conv.insert(0, Fraction(0, 1))
    return list(zip(conv, conv[1:]))


def gp_fraction(x: Fraction) -> str:
    if x.denominator == 1:
        return str(x.numerator)
    return f"{x.numerator}/{x.denominator}"


def gp_paths(a: int, c: int) -> str:
    edges = farey_edges(Fraction(a, c))
    return "[" + ", ".join(f"[{gp_fraction(u)}, {gp_fraction(v)}]" for u, v in edges) + "]"


def emit_gp(triples: list[Triple]) -> str:
    header = r"""\\ Frey modular-symbol scan generated by make_pari_symbol_scan.py
\\p 50

absreal(x) = abs(x + 0.0);
frey_curve(a, b) = ellinit([0, b-a, 0, -a*b, 0]);

report_symbol_frame(label, qabc, a, b, paths) =
{
  my(c = a + b);
  my(E = frey_curve(a, b));
  my(N = ellglobalred(E)[1]);
  my(w = ellrootno(E));
  my(ms = msfromell(E, 0));
  my(M = ms[1]);
  my(x = ms[2]);
  my(xp = x[1]);
  my(xm = x[2]);
  my(windp = mseval(M, xp, [0, oo]));
  my(windm = mseval(M, xm, [0, oo]));
  my(maxp = 0.0, maxm = 0.0, maxboth = 0.0);

  for(i = 1, #paths,
    my(vp = mseval(M, xp, paths[i]));
    my(vm = mseval(M, xm, paths[i]));
    my(ap = absreal(vp));
    my(am = absreal(vm));
    my(ab = max(ap, am));
    if(ap > maxp, maxp = ap);
    if(am > maxm, maxm = am);
    if(ab > maxboth, maxboth = ab);
  );

  printf("SUMMARY | %s | q=%.3f | a=%d | b=%d | c=%d | Ncond=%d | rootno=%d | dim=%d | edges=%d | winding_plus=%Ps | winding_minus=%Ps | max_xplus=%.12g | max_xminus=%.12g | max_frame=%.12g\n",
         label, qabc, a, b, c, N, w, msdim(M), #paths, windp, windm, maxp, maxm, maxboth);
};

"""
    calls = []
    for t in triples:
        calls.append(
            f'report_symbol_frame("{t.label}", {t.q:.3f}, {t.a}, {t.b}, {gp_paths(t.a, t.c)});'
        )
    return header + "\n".join(calls) + "\n\nquit;\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=len(TRIPLES))
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()

    code = emit_gp(TRIPLES[: args.limit])
    if args.out:
        args.out.write_text(code, encoding="utf-8")
    else:
        print(code)


if __name__ == "__main__":
    main()
